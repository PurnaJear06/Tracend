-- The auth_user_create_account trigger auto-inserts the user_accounts
-- row on the auth.users insert — no explicit account insert needed (and
-- an explicit one would collide on id).
create function pg_temp.seed_user(v_user uuid) returns void language plpgsql as $$
begin
  insert into auth.users(id, role) values (v_user, 'authenticated');
end $$;

-- Sessions need the plan/version/workout FK chain.
create function pg_temp.seed_sessions(
  v_user uuid, v_fix jsonb
) returns void language plpgsql as $$
declare
  s jsonb;
  v_plan uuid := gen_random_uuid();
  version_id uuid := gen_random_uuid();
  workout_id uuid := gen_random_uuid();
begin
  if jsonb_array_length(v_fix->'sessions') = 0 then return; end if;

  insert into public.training_plans(id, user_id, title, source)
  values (v_plan, v_user, 'Parity plan', 'imported');
  insert into public.training_plan_versions(
    id, user_id, plan_id, version_number, status, block_weeks, sessions_per_week,
    prescription, rationale, approved_at, effective_date)
  values (version_id, v_user, v_plan, 1, 'active', 8, 6, '{}',
    'Approved plan', now(), current_date - 30);
  insert into public.planned_workouts(
    id, user_id, plan_version_id, name, workout_order, preferred_weekday,
    objective, estimated_minutes, warm_up_guidance, cool_down_guidance)
  values (workout_id, v_user, version_id, 'Parity session', 1, 1, 'Load',
    60, 'Warm up', 'Cool down');

  for s in select value from jsonb_array_elements(v_fix->'sessions') loop
    insert into public.workout_sessions(
      user_id, plan_version_id, planned_workout_id, state, local_date, timezone,
      idempotency_key, session_effort, duration_seconds, logging_completeness,
      completed_at)
    values (v_user, version_id, workout_id, 'completed',
      (s->>'date')::date, 'Asia/Kolkata', gen_random_uuid(),
      (s->>'effort')::numeric, (s->>'duration_seconds')::int, 1.0, now());
  end loop;
end $$;

-- Health days. present_types is derived from the keys actually present
-- (array_remove of case-when nulls), which the parity assertions never
-- read — they read the computed columns.
create function pg_temp.seed_health(
  v_user uuid, v_fix jsonb
) returns void language plpgsql as $$
declare
  d jsonb;
  v_types text[];
begin
  for d in select value from jsonb_array_elements(v_fix->'health_days') loop
    v_types := array_remove(array[
      case when d ? 'hrv_ms' then 'hrv_sdnn' end,
      case when d ? 'resting_hr_bpm' then 'resting_heart_rate' end,
      case when d ? 'sleep_minutes' then 'sleep' end,
      case when d ? 'resp_rate_bpm' then 'resp_rate' end,
      case when d ? 'weight_kg' then 'weight' end
    ], null);

    insert into public.daily_health_summaries(
      user_id, local_date, timezone, present_types, source_refs,
      source_checksum, completeness, observed_through, last_synced_at,
      hrv_value_ms, hrv_metric, hrv_unit,
      resting_heart_rate_bpm, respiratory_rate_bpm,
      sleep_minutes, sleep_awake_minutes, sleep_deep_minutes, sleep_rem_minutes
    )
    values (
      v_user, (d->>'date')::date, 'Asia/Kolkata', v_types,
      '[]'::jsonb, md5(random()::text) || md5(random()::text),
      'partial', now(), now(),
      nullif(d->>'hrv_ms','')::numeric,
      case when d ? 'hrv_ms' then 'sdnn' end,
      case when d ? 'hrv_ms' then 'ms' end,
      nullif(d->>'resting_hr_bpm','')::numeric,
      nullif(d->>'resp_rate_bpm','')::numeric,
      nullif(d->>'sleep_minutes','')::int,
      nullif(d->>'sleep_awake_minutes','')::int,
      nullif(d->>'sleep_deep_minutes','')::int,
      nullif(d->>'sleep_rem_minutes','')::int
    );
  end loop;
end $$;

create function pg_temp.seed_weights(
  v_user uuid, v_fix jsonb
) returns void language plpgsql as $$
declare
  w jsonb;
begin
  for w in select value from jsonb_array_elements(v_fix->'weight_days') loop
    insert into public.body_measurements(user_id, measured_on, source, weight_kg)
    values (v_user, (w->>'date')::date, 'manual', (w->>'weight_kg')::numeric);
  end loop;
end $$;

-- Seed one fixture (user id per fixture; fixtures run in their own
-- transaction, so ids never collide across files).
create function pg_temp.seed_fixture(v_fix jsonb, v_user uuid)
returns void language plpgsql as $$
begin
  perform pg_temp.seed_user(v_user);
  perform pg_temp.seed_health(v_user, v_fix);
  perform pg_temp.seed_sessions(v_user, v_fix);
  perform pg_temp.seed_weights(v_user, v_fix);
end $$;

-- ─────────────────────────────────────────────────────────────────────────
-- Layer 1 — the expected-oracle drift alarm.
--
-- Runs the seeded fixture through the production SQL and compares every
-- scored output against the fixture's embedded `expected` block at the
-- SQL's own rounding scale. One TAP row per field (pgTAP test functions
-- return text; this set-returning helper emits them through `return next`).
-- ─────────────────────────────────────────────────────────────────────────

create function pg_temp.assert_expected(v_fix jsonb, v_user uuid, v_name text)
returns setof text language plpgsql as $$
declare
  v_out jsonb;
  v_e jsonb := v_fix->'expected';
  v_s jsonb;
  v_b jsonb;
begin
  v_out := public.compute_daily_metrics(
    v_user, (v_fix->>'target_date')::date, 'Asia/Kolkata');
  v_s := v_out->'scores';
  v_b := v_s->'recovery_breakdown';

  -- Integers (SQL rounds these itself; expected blocks carry the same
  -- scale). -9999 sentinel = null on either side, outside every range.
  return next is(
    coalesce((v_s->>'recovery')::numeric, -9999),
    coalesce((v_e->>'recovery')::numeric, -9999),
    v_name || ': recovery');

  return next is(
    coalesce((v_s->>'sleep_quality')::numeric, -9999),
    coalesce((v_e->>'sleep_quality')::numeric, -9999),
    v_name || ': sleep_quality');

  return next is(
    coalesce((v_s->>'sleep_debt_minutes')::numeric, -9999),
    coalesce((v_e->>'sleep_debt_minutes')::numeric, -9999),
    v_name || ': sleep_debt_minutes');

  return next is(
    coalesce((v_s->>'daily_strain')::numeric, -9999),
    coalesce((v_e->>'daily_strain')::numeric, -9999),
    v_name || ': daily_strain');

  return next is(
    coalesce((v_s->>'acwr')::numeric, -9999),
    coalesce((v_e->>'acwr')::numeric, -9999),
    v_name || ': acwr');

  return next is(
    coalesce((v_s->>'training_monotony')::numeric, -9999),
    coalesce((v_e->>'monotony')::numeric, -9999),
    v_name || ': training_monotony');

  -- Text.
  return next is(
    v_out->>'data_confidence',
    v_e->>'data_confidence',
    v_name || ': data_confidence');

  -- Missing components: exact array equality (order + duplicates).
  return next is(
    v_b->'missing_components' = v_e->'missing_components',
    true,
    v_name || ': missing_components');

  -- Z-scores (SQL emits all five keys, rounded to 3 decimals).
  return next ok(
    abs(coalesce((v_b->>'hrv_z')::numeric, -9999)
      - coalesce((v_e->>'hrv_z')::numeric, -9999)) <= 0.005,
    format('%s: hrv_z (sql %s vs expected %s)', v_name,
      coalesce(v_b->>'hrv_z', 'absent'), coalesce(v_e->>'hrv_z', 'absent')));

  return next ok(
    abs(coalesce((v_b->>'rhr_z')::numeric, -9999)
      - coalesce((v_e->>'rhr_z')::numeric, -9999)) <= 0.005,
    format('%s: rhr_z (sql %s vs expected %s)', v_name,
      coalesce(v_b->>'rhr_z', 'absent'), coalesce(v_e->>'rhr_z', 'absent')));

  return next ok(
    abs(coalesce((v_b->>'sleep_z')::numeric, -9999)
      - coalesce((v_e->>'sleep_z')::numeric, -9999)) <= 0.005,
    format('%s: sleep_z (sql %s vs expected %s)', v_name,
      coalesce(v_b->>'sleep_z', 'absent'), coalesce(v_e->>'sleep_z', 'absent')));

  return next ok(
    abs(coalesce((v_b->>'resp_rate_z')::numeric, -9999)
      - coalesce((v_e->>'resp_rate_z')::numeric, -9999)) <= 0.005,
    format('%s: resp_rate_z (sql %s vs expected %s)', v_name,
      coalesce(v_b->>'resp_rate_z', 'absent'),
      coalesce(v_e->>'resp_rate_z', 'absent')));

  return next ok(
    abs(coalesce((v_b->>'prev_strain_z')::numeric, -9999)
      - coalesce((v_e->>'prev_strain_z')::numeric, -9999)) <= 0.005,
    format('%s: prev_strain_z (sql %s vs expected %s)', v_name,
      coalesce(v_b->>'prev_strain_z', 'absent'),
      coalesce(v_e->>'prev_strain_z', 'absent')));

  -- Sub-score exposure: the SQL emits the breakdown object (and the
  -- individual subs inside it) only when ALL FOUR subs are computable.
  -- The expected block exposes each computable sub independently, so
  -- this row pins the exposure rule itself. Presence is read via ->>
  -- (a JSON null value flattens to SQL NULL there; -> keeps it as a
  -- non-null jsonb, which would make the check lie).
  return next is(
    (v_s->>'sleep_breakdown') is not null,
    (v_e->>'duration_score') is not null
      and (v_e->>'efficiency_score') is not null
      and (v_e->>'restorative_score') is not null
      and (v_e->>'consistency_score') is not null,
    v_name || ': sleep_breakdown exposure (all four subs or none)');

  -- Sub-scores, compared only when exposed (partial nights are pinned
  -- through the composite + breakdown-missing rows above and below).
  return next ok(
    case when (v_s->>'sleep_breakdown') is null then true
      else abs((v_s->'sleep_breakdown'->>'duration_score')::numeric
        - (v_e->>'duration_score')::numeric) <= 0.05 end,
    format('%s: duration_score (sql %s vs expected %s)', v_name,
      coalesce(v_s->'sleep_breakdown'->>'duration_score', 'not exposed'),
      coalesce(v_e->>'duration_score', 'absent')));

  return next ok(
    case when (v_s->>'sleep_breakdown') is null then true
      else abs((v_s->'sleep_breakdown'->>'efficiency_score')::numeric
        - (v_e->>'efficiency_score')::numeric) <= 0.05 end,
    format('%s: efficiency_score (sql %s vs expected %s)', v_name,
      coalesce(v_s->'sleep_breakdown'->>'efficiency_score', 'not exposed'),
      coalesce(v_e->>'efficiency_score', 'absent')));

  return next ok(
    case when (v_s->>'sleep_breakdown') is null then true
      else abs((v_s->'sleep_breakdown'->>'restorative_score')::numeric
        - (v_e->>'restorative_score')::numeric) <= 0.05 end,
    format('%s: restorative_score (sql %s vs expected %s)', v_name,
      coalesce(v_s->'sleep_breakdown'->>'restorative_score', 'not exposed'),
      coalesce(v_e->>'restorative_score', 'absent')));

  return next ok(
    case when (v_s->>'sleep_breakdown') is null then true
      else abs((v_s->'sleep_breakdown'->>'consistency_score')::numeric
        - (v_e->>'consistency_score')::numeric) <= 0.05 end,
    format('%s: consistency_score (sql %s vs expected %s)', v_name,
      coalesce(v_s->'sleep_breakdown'->>'consistency_score', 'not exposed'),
      coalesce(v_e->>'consistency_score', 'absent')));

  -- breakdown-missing: an absent key and a JSON null are the same state
  -- here (no valid sleep night); normalize both sides to jsonb 'null'
  -- before comparing, then compare as jsonb (array order preserved).
  return next is(
    (coalesce(v_s->'sleep_breakdown_missing', 'null'::jsonb))
      is not distinct from
    (coalesce(v_e->'sleep_breakdown_missing', 'null'::jsonb)),
    true,
    v_name || ': sleep_breakdown_missing');
end $$;

