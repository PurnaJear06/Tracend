-- Pass 5 — reference parity (2026-09-08, hardened 2026-09-09).
--
-- The Dart reference implementation (test/reference/recovery_reference.dart,
-- written from docs/ALGORITHMS.md, not from SQL) and the production SQL
-- (compute_user_baselines / compute_daily_metrics, migration
-- 20260907160000) must produce the same numbers on the same inputs. This
-- test seeds the shared oracle fixtures (test/reference/fixtures/*.json —
-- shipped into the container at /fixtures by scripts/test-db.sh) into the
-- database and asserts the SQL output matches the reference's pins.
--
-- TWO assertion layers, both mandatory:
-- 1. The `expected` oracle block embedded in every fixture (generated by
--    tool/generate_expected.dart from the Dart reference). assert_expected()
--    runs the seeded fixture through compute_daily_metrics and compares
--    every scored output — recovery, the five z-scores, sleep quality, the
--    breakdown-exposure rule, the four sub-scores, breakdown-missing, debt,
--    strain, ACWR, monotony, data confidence, missing components — at the
--    SQL's own rounding scale. A sign flip, a weight typo, or a gate change
--    in EITHER implementation breaks these rows. That is the drift alarm.
-- 2. The independent hand-computed anchors (62, -0.294, 1.95, 2.27, 85.6,
--    the x3 ln-invariance twin) — derived outside both implementations,
--    so the oracle blocks can never go quietly circular.
--
-- Sub-score exposure rule: the SQL emits the sleep_breakdown object (and
-- with it the individual sub-scores) ONLY when all four subs are
-- computable; the reference exposes each computable sub individually. So
-- the SQL side pins the exposure rule itself (breakdown present ⟺ all
-- four expected subs non-null), compares each sub within ε when exposed,
-- and pins the renormalized composite + sleep_breakdown_missing on
-- partial nights — which still catches a duration/consistency drift
-- through the composite it feeds.
--
-- Seeding pattern (the fixtures are client-side psql variables, so each
-- block does its own \set + seeding + assertions):
--   \set fixture_json `cat /fixtures/<name>.json`
--   select pg_temp.seed_fixture(:'fixture_json', '<user>');
--   select * from pg_temp.assert_expected(:'fixture_json'::jsonb, '<user>', '<label>');
--
-- Rounding contract: the SQL emits z-scores rounded to 3 decimals, sleep
-- sub-scores to 1, ACWR/monotony/strain to 2, recovery/quality/debt as
-- integers; the expected blocks carry the same scales. z/sub comparisons
-- use ε 0.005 / 0.05; integers compare exactly; a NULL on either side of
-- an exact compare uses the -9999 sentinel (outside every field's range).

