/// Today's meal plan (null when it failed to load) and confirmed meals.
typedef TodayMeals = ({NutritionSchedule? schedule, List<MealEntry> meals});

class TodayScreen extends StatefulWidget {
  const TodayScreen({
    required this.environment,
    this.onSignOut,
    this.workouts,
    this.health = const ManualHealthRepository(),
    this.coach = const FixtureCoachRepository(),
    this.brief = const FixtureDailyBriefRepository(),
    this.nutrition = const FixtureNutritionRepository(),
    this.queueFactory,
    this.checkInSender,
    this.onOpenNutrition,
    this.onOpenTrain,
    this.aiConsent,
    this.checkInGate,
    this.planChanges,
    this.widgetPublisher,
    this.widgetTaps,
    this.dayAdjustment,
    this.onTalkToCoach,
    this.workoutLogs,
    this.clock = DateTime.now,
    super.key,
  });

  final AppEnvironment environment;
  final Future<void> Function()? onSignOut;
  final WorkoutRepository? workouts;
  final HealthRepository health;
  final CoachRepository coach;
  final DailyBriefRepository brief;
  final NutritionRepository nutrition;

  /// Builds the pending-check-in replay queue. Defaults to the real
  /// SharedPreferences-backed queue; tests inject a fake.
  final CheckInQueue? Function()? queueFactory;

  /// Performs the `save_daily_check_in` RPC during replay. Defaults to the
  /// real Supabase client; tests inject a recording fake.
  final CheckInSend? checkInSender;

  /// Shell wiring: switch to the Nutrition tab ("Log a meal").
  final VoidCallback? onOpenNutrition;

  /// Shell wiring: switch to the Train tab. "Open in Train" on today's
  /// session opens Train when this is wired and the workout itself
  /// otherwise.
  final VoidCallback? onOpenTrain;

  /// The daily decision is generated by the AI provider only while this is
  /// granted. Null without a backend, where nothing is sent.
  final AiCoachingConsentController? aiConsent;

  /// The shell's morning check-in gate. Today sets it while today's
  /// check-in is missing; without it, the hero offers a "Check in" chip.
  final CheckInGate? checkInGate;

  /// Reloads the targets and today's brief when a Coach proposal changed the
  /// plan, the targets or the goal.
  final PlanChanges? planChanges;

  /// Writes Today's snapshot for the Home Screen and Lock Screen widgets each
  /// time the brief loads; null where there are no widgets.
  final TodayWidgetPublisher? widgetPublisher;

  /// Notifies when a tapped widget brought the app forward. Today then reloads
  /// if what it shows is a day old or older than half an hour, so the widgets
  /// are fresh by the time the athlete looks.
  final Listenable? widgetTaps;

  /// Today's same-day readiness adjustment, shared with Train. Null without a
  /// backend, where there is none.
  final DayAdjustmentController? dayAdjustment;

  /// Shell wiring: open Coach with a question in the box ("Talk to Coach" on
  /// the readiness card).
  final ValueChanged<String>? onTalkToCoach;

  /// Told when Today saves a workout the athlete left unfinished, so Train
  /// reloads its week.
  final WorkoutLogChanges? workoutLogs;

  /// The time Today measures the age of its brief by.
  final DateTime Function() clock;

  @override
  State<TodayScreen> createState() => _TodayScreenState();
}

class _TodayScreenState extends State<TodayScreen> {
  late Future<HealthHistory> _healthHistory;
  late Future<DailyBrief> _brief;
  late Future<NutritionTargets?> _targets;
  late Future<TodayMeals> _meals;
  late Future<CoachDecision?> _latestDecision;
  bool _syncing = false;

  /// The workout the server offers back (logged, never finished), and
  /// whether an answer to it is on its way.
  UnfinishedWorkout? _unfinished;
  bool _answeringUnfinished = false;

  /// Which read of the offer started last, and which answer came last. A
  /// read that finishes after a newer read started or an answer was given
  /// (a slow one from before it) is ignored, so it never brings back a card
  /// the athlete already answered.
  int _unfinishedLoads = 0;

  /// Today's check-in as this phone knows it: saved (also when only queued
  /// offline) or put off with "Not today". Each holds the day it was set.
  String? _checkedInOn;
  String? _skippedOn;

  /// The server's today (`YYYY-MM-DD`), once the readiness controller learned
  /// it, whatever the phone's date says. The brief is loaded for it, and a
  /// check-in is saved under it, so the card, the numbers, the session and the
  /// check-in all describe one day. Until it is known the phone's date is used.
  String? _serverDay;

  /// The day and route of the safety sheet already shown, so it opens once.
  String? _safetyShown;
  DailyBrief? _lastBrief;
  static const _checkedInKey = 'today_check_in_saved_on';
  static const _skippedKey = 'today_check_in_skipped_on';

  /// What the last sync could not refresh, shown on the hero until a sync
  /// succeeds.
  String? _syncIssue;

  /// Auto health sync runs at most once per 30 minutes and never triggers a
  /// permission prompt: it fires only when a previous sync already succeeded.
  static const _autoSyncInterval = Duration(minutes: 30);

  bool get _aiAllowed => widget.aiConsent?.granted ?? true;

  /// Granting AI coaching brings today's decision without waiting for a sync.
  void _consentChanged() {
    setState(() {});
    if (_aiAllowed) _refreshDecisionAfterEvidence();
  }

  @override
  void didUpdateWidget(TodayScreen oldWidget) {
    super.didUpdateWidget(oldWidget);
    if (oldWidget.aiConsent != widget.aiConsent) {
      oldWidget.aiConsent?.removeListener(_consentChanged);
      widget.aiConsent?.addListener(_consentChanged);
    }
  }

  late final ResumeObserver _resume = ResumeObserver(_onResume);

  /// Back at the front: reload what is old, pull the night's Apple Health
  /// data if the last sync was a while ago, and deliver check-ins that waited
  /// for a connection.
  void _onResume() {
    if (!mounted) return;
    _reloadIfStale();
    unawaited(_autoSyncHealthIfNeeded());
    unawaited(_replayPendingCheckIn());
  }

  /// When the brief last arrived; null until the first one does.
  DateTime? _briefLoadedAt;

  /// A brief shown for longer than this, or from another day, is reloaded
  /// when the app comes back to the front.
  static const _staleBriefAfter = Duration(minutes: 30);

  /// Returning to the app (or a tapped widget bringing it forward) reloads
  /// the brief, targets and meals when none has arrived yet, the last one is
  /// over half an hour old, or the local day has changed. The new brief is
  /// what the widgets get: an old one is never written again.
  void _reloadIfStale() {
    if (!mounted) return;
    unawaited(widget.dayAdjustment?.refreshIfStale());
    final loadedAt = _briefLoadedAt;
    final brief = _lastBrief;
    final now = widget.clock();
    final stale =
        loadedAt == null ||
        brief == null ||
        now.difference(loadedAt) > _staleBriefAfter ||
        brief.localDate != _dateKey(_briefDay());
    if (!stale) return;
    _reloadHealth();
    setState(() {
      _targets = widget.nutrition.loadTargets();
      _meals = _loadMeals();
      _brief = _loadBrief();
    });
    unawaited(_loadUnfinished());
  }

  @override
  void dispose() {
    _resume.detach();
    widget.widgetTaps?.removeListener(_reloadIfStale);
    widget.aiConsent?.removeListener(_consentChanged);
    widget.planChanges?.removeListener(_planChanged);
    widget.dayAdjustment?.removeListener(_dayAdjustmentChanged);
    super.dispose();
  }

  void _planChanged() {
    if (!mounted) return;
    unawaited(widget.dayAdjustment?.load());
    setState(() {
      _targets = widget.nutrition.loadTargets();
      _brief = _loadBrief();
    });
  }

  @override
  void initState() {
    super.initState();
    _resume.attach();
    widget.widgetTaps?.addListener(_reloadIfStale);
    widget.aiConsent?.addListener(_consentChanged);
    widget.planChanges?.addListener(_planChanged);
    widget.dayAdjustment?.addListener(_dayAdjustmentChanged);
    _reloadHealth();
    unawaited(widget.dayAdjustment?.load());
    _targets = widget.nutrition.loadTargets();
    _meals = _loadMeals();
    _brief = _loadBrief();
    _latestDecision = widget.coach.loadLatest();
    _restoreCheckInDays();
    _autoSyncHealthIfNeeded();
    _replayPendingCheckIn();
    unawaited(_loadUnfinished());
  }

  UnfinishedWorkoutRepository? get _unfinishedSource {
    final source = widget.workouts;
    return source is UnfinishedWorkoutRepository
        ? source as UnfinishedWorkoutRepository
        : null;
  }

  /// Asks which workout, if any, was logged and left unfinished. A failed
  /// read keeps what is shown: the offer is a convenience, never a gate.
  Future<void> _loadUnfinished() async {
    final source = _unfinishedSource;
    if (source == null) return;
    final load = ++_unfinishedLoads;
    try {
      final workout = await source.loadUnfinishedWorkout();
      if (mounted && load == _unfinishedLoads) {
        setState(() => _unfinished = workout);
      }
    } catch (error) {
      logNonCritical(error, 'unfinished workout');
    }
  }

  /// "Save workout": asks how hard it was, then puts it in the history on
  /// its own day. Nothing is saved until the athlete answers.
  Future<void> _saveUnfinished(UnfinishedWorkout workout) async {
    final source = _unfinishedSource;
    if (source == null || _answeringUnfinished) return;
    final effort = await showWorkoutFinishSheet(
      context,
      workoutName: workout.name,
      unloggedSets: workout.unloggedSets,
      saving: true,
    );
    if (effort == null || !mounted) return;
    setState(() => _answeringUnfinished = true);
    try {
      await source.saveUnfinishedWorkout(workout, sessionEffort: effort);
      if (!mounted) return;
      _unfinishedLoads++;
      setState(() {
        _unfinished = null;
        _brief = _loadBrief();
      });
      // Train counts the saved workout in its week and its history.
      widget.workoutLogs?.announce();
      TracendToast.show(
        context,
        '${workout.name} saved to ${dayAndDate(workout.localDate)}.',
        icon: CupertinoIcons.checkmark_alt,
      );
    } on UnfinishedWorkoutGone {
      if (!mounted) return;
      TracendToast.show(
        context,
        'This workout can no longer be saved.',
        icon: CupertinoIcons.exclamationmark_triangle,
      );
    } catch (error) {
      logNonCritical(error, 'unfinished workout not saved');
      if (!mounted) return;
      TracendToast.show(
        context,
        'Could not save the workout. Try again.',
        icon: CupertinoIcons.exclamationmark_triangle,
      );
    } finally {
      if (mounted) setState(() => _answeringUnfinished = false);
    }
    unawaited(_loadUnfinished());
    // Saving or discarding a session changes whether today's can still be
    // adjusted.
    unawaited(widget.dayAdjustment?.load());
  }

  /// "Discard": after a confirmation, keeps the workout out of the history
  /// for good.
  Future<void> _discardUnfinished(UnfinishedWorkout workout) async {
    final source = _unfinishedSource;
    if (source == null || _answeringUnfinished) return;
    final confirmed = await showTracendConfirm(
      context,
      title: 'Discard ${workout.name}?',
      message:
          'It will not count in your history or your training load. This '
          'cannot be undone.',
      confirmLabel: 'Discard',
      destructive: true,
    );
    if (!confirmed || !mounted) return;
    setState(() => _answeringUnfinished = true);
    try {
      await source.discardUnfinishedWorkout(workout);
      if (!mounted) return;
      _unfinishedLoads++;
      setState(() => _unfinished = null);
    } on UnfinishedWorkoutGone {
      if (!mounted) return;
      TracendToast.show(
        context,
        'This workout is no longer offered.',
        icon: CupertinoIcons.exclamationmark_triangle,
      );
    } catch (error) {
      logNonCritical(error, 'unfinished workout not discarded');
      if (!mounted) return;
      TracendToast.show(
        context,
        'Could not discard the workout. Try again.',
        icon: CupertinoIcons.exclamationmark_triangle,
      );
    } finally {
      if (mounted) setState(() => _answeringUnfinished = false);
    }
    unawaited(_loadUnfinished());
    // Saving or discarding a session changes whether today's can still be
    // adjusted.
    unawaited(widget.dayAdjustment?.load());
  }

  bool _replaying = false;

  /// Deliver any check-in queued while offline: the sheet persists the
  /// envelope before its RPC, and this replays each with the same idempotency
  /// key (the server deduplicates). The stored answer day's date is sent as
  /// recorded — a check-in belongs to the day it was answered, never
  /// re-dated to today. It runs at launch and each time the app comes back
  /// to the front. Silent while offline: the envelope stays stored and the
  /// next resume or launch retries. A check-in the server refuses for good is
  /// dropped, reported by its code, and the athlete is told. On success the
  /// brief reloads because the check-in now colors today's coaching context.
  Future<void> _replayPendingCheckIn() async {
    if (!widget.environment.hasSupabaseConfiguration || _replaying) return;
    _replaying = true;
    try {
      final queue = await _resolveQueue();
      if (queue == null) return;
      final replay = await queue.replay(_replaySender);
      for (final refusal in replay.refused) {
        reportNonCritical(refusal.error, null, 'Queued check-in refused');
      }
      if (replay.refused.isNotEmpty && mounted) {
        TracendToast.show(
          context,
          replay.refused.length == 1
              ? 'The check-in from ${_refusedDay(replay.refused.single)} '
                    'could not be saved and was dropped.'
              : '${replay.refused.length} earlier check-ins could not be saved '
                    'and were dropped.',
          icon: CupertinoIcons.exclamationmark_triangle,
        );
      }
      if (replay.deliveredAny && mounted) {
        setState(() {
          _brief = _loadBrief();
        });
        // The replayed check-in is what today's call rests on, and it may send
        // the athlete to a professional: read it and say so, as after an
        // online save.
        final readiness = widget.dayAdjustment;
        if (readiness != null) {
          await readiness.load();
          if (mounted) await _showSafetyOnce(readiness);
        }
        // The replayed check-in is new evidence: today's decision may have
        // been generated without it and must be refreshed.
        await _refreshDecisionAfterEvidence();
      }
    } on Exception {
      // Keep the envelopes; retried on the next resume or launch.
    } finally {
      _replaying = false;
    }
  }

  String _refusedDay(CheckInRefusal refusal) {
    final day = DateTime.tryParse(refusal.localDate);
    return day == null ? refusal.localDate : dayAndDate(day);
  }

  Future<bool> _replaySender(
    String localDate,
    String timezone,
    String idempotencyKey,
    Map<String, dynamic> payload,
  ) async {
    if (widget.checkInSender != null) {
      return widget.checkInSender!(
        localDate,
        timezone,
        idempotencyKey,
        payload,
      );
    }
    await Supabase.instance.client.rpc(
      'save_daily_check_in',
      params: {
        'local_date': localDate,
        'timezone': timezone,
        'idempotency_key': idempotencyKey,
        'payload': payload,
      },
    );
    return true;
  }

  Future<CheckInQueue?> _resolveQueue() async {
    if (widget.queueFactory != null) return widget.queueFactory!();
    final preferences = await SharedPreferences.getInstance();
    return CheckInQueue(
      preferences,
      userId: Supabase.instance.client.auth.currentUser?.id,
    );
  }

  /// Today's meal plan and confirmed meals for the fuel rail. A failure
  /// leaves the schedule null so the card says the plan did not load.
  Future<TodayMeals> _loadMeals() async {
    final nutrition = widget.nutrition;
    final day = _briefDay();
    _mealsRequestedFor = _dateKey(day);
    try {
      final meals = await nutrition.loadMeals(day);
      final schedule = nutrition is NutritionScheduleRepository
          ? await (nutrition as NutritionScheduleRepository).loadSchedule(day)
          : const NutritionSchedule(title: '', items: []);
      return (schedule: schedule, meals: meals);
    } catch (error) {
      logNonCritical(error, 'Today: meals failed');
      return (schedule: null, meals: const <MealEntry>[]);
    }
  }

  /// Which brief load started last. A load that finishes after a newer one
  /// started (a slow request from before midnight, say) is ignored, so it
  /// never overwrites the newer day's brief, gate or widgets.
  int _briefLoads = 0;

  /// The day the brief is loaded for: the server's once it is known, else the
  /// phone's.
  DateTime _briefDay() {
    final day = _serverDay == null ? null : DateTime.tryParse(_serverDay!);
    return day ?? widget.clock();
  }

  /// The day of the newest brief request, `YYYY-MM-DD`.
  String? _briefRequestedFor;

  /// The day of the newest meals request, `YYYY-MM-DD`.
  String? _mealsRequestedFor;

  /// The athlete's day for the check-in gate and its saved marks: the
  /// server's when known, else the brief's, else the phone's.
  String _dayKey() =>
      _serverDay ?? _lastBrief?.localDate ?? _dateKey(widget.clock());

  /// The day the coaching decision must be dated for to be current: the
  /// server's once it is known, else the phone's. (The brief's date is not
  /// used: before the server's day is known it is the phone's own request.)
  String _decisionDay() => _dateKey(_briefDay());

  /// Follows the server's day. It is recorded as soon as the controller learns
  /// it, whether or not the brief has arrived, and the brief and today's meals
  /// are loaded again when the newest request was for another day, whichever
  /// of the two finishes first.
  void _dayAdjustmentChanged() {
    final day = widget.dayAdjustment?.serverDay;
    if (!mounted || day == null) return;
    final rolledOver = _serverDay != null && _serverDay != day;
    _serverDay = day;
    // The server's day moved on while Today was open (midnight where the
    // athlete is): yesterday's decision is no longer today's.
    if (rolledOver) unawaited(_refreshDecisionAfterEvidence());
    final briefStale = _briefRequestedFor != day;
    final mealsStale = _mealsRequestedFor != day;
    if (!briefStale && !mealsStale) return;
    setState(() {
      if (briefStale) _brief = _loadBrief();
      if (mealsStale) _meals = _loadMeals();
    });
  }

  /// Loads the brief and, once it arrives, sets the check-in gate from it and
  /// hands it to the widgets.
  Future<DailyBrief> _loadBrief() {
    final load = ++_briefLoads;
    final day = _briefDay();
    _briefRequestedFor = _dateKey(day);
    final future = widget.brief.load(day);
    future.then((brief) {
      if (!mounted || load != _briefLoads) return;
      _lastBrief = brief;
      _briefLoadedAt = widget.clock();
      _updateGate();
      unawaited(_publishWidgets(brief));
    }, onError: (_) {});
    return future;
  }

  /// Newest publish wins: targets can arrive after the brief, and a slow
  /// older publish must not overwrite a newer one.
  int _publishes = 0;

  /// Writes [brief] with the plan's targets and the check-in state for the
  /// Home Screen and Lock Screen widgets. Without targets (they did not load)
  /// only what was eaten shows. Silent: the widgets are a convenience.
  Future<void> _publishWidgets(DailyBrief brief) async {
    final publisher = widget.widgetPublisher;
    if (publisher == null) return;
    final publish = ++_publishes;
    NutritionTargets? targets;
    try {
      targets = await _targets;
    } catch (_) {
      // Unknown targets leave the widgets showing what was eaten.
    }
    if (!mounted || publish != _publishes) return;
    await publisher.publish(
      brief: brief,
      targets: targets,
      checkedIn: _checkedIn(brief),
      loadedAt: _briefLoadedAt,
    );
  }

  bool _checkedIn(DailyBrief brief) =>
      brief.checkIn != null || _checkedInOn == brief.localDate;

  void _updateGate() {
    final brief = _lastBrief;
    widget.checkInGate?.update(
      required:
          brief != null && !_checkedIn(brief) && _skippedOn != brief.localDate,
      onCheckIn: _openCheckIn,
      onSkip: _skipCheckIn,
    );
  }

  Future<void> _restoreCheckInDays() async {
    try {
      final preferences = await SharedPreferences.getInstance();
      if (!mounted) return;
      setState(() {
        _checkedInOn = preferences.getString(_checkedInKey);
        _skippedOn = preferences.getString(_skippedKey);
      });
      _updateGate();
      final brief = _lastBrief;
      if (brief != null) unawaited(_publishWidgets(brief));
    } catch (_) {
      // Without stored days the gate follows the brief alone.
    }
  }

  Future<void> _rememberDay(String key, String day) async {
    try {
      final preferences = await SharedPreferences.getInstance();
      await preferences.setString(key, day);
    } catch (_) {
      // The gate still opens for this session.
    }
  }

  /// "Not today": the tab bar comes back until tomorrow.
  void _skipCheckIn() {
    final day = _dayKey();
    setState(() => _skippedOn = day);
    _updateGate();
    _rememberDay(_skippedKey, day);
  }

  void _reloadHealth() {
    _healthHistory = widget.health.loadHistory();
  }

  void _reloadBriefAndHealth() {
    _reloadHealth();
    // Sleep and recovery that just arrived can change today's call.
    unawaited(widget.dayAdjustment?.load());
    setState(() {
      _brief = _loadBrief();
      _targets = widget.nutrition.loadTargets();
      _meals = _loadMeals();
    });
    unawaited(_loadUnfinished());
  }

  bool _autoSyncing = false;

  Future<void> _autoSyncHealthIfNeeded() async {
    if (!widget.environment.hasSupabaseConfiguration || _autoSyncing) return;
    _autoSyncing = true;
    try {
      final status = await widget.health.loadStatus();
      final last = status.lastSuccessfulSync;
      if (last == null) return; // never connected -> manual via profile only
      if (widget.clock().difference(last) < _autoSyncInterval) return;
      await widget.health.sync();
      if (mounted) _reloadBriefAndHealth();
    } catch (_) {
      // Silent: the hero sync button stays available for an explicit retry.
    } finally {
      _autoSyncing = false;
    }
  }

  /// Sync everything: Apple Health (when connected), the daily brief, and
  /// today's coaching decision. Each stage fails independently and the result
  /// message reports exactly what could not be refreshed — a HealthKit read
  /// that returns `unavailable` counts as a failure, and a never-connected
  /// Apple Health is reported as skipped, never as "up to date".
  Future<void> _syncEverything() async {
    if (_syncing) return;
    setState(() => _syncing = true);
    final failures = <String>[];
    var healthSkipped = false;
    try {
      try {
        final status = await widget.health.loadStatus();
        if (status.lastSuccessfulSync != null) {
          final synced = await widget.health.sync();
          if (synced.state == HealthConnectionState.unavailable) {
            failures.add('Apple Health');
          }
        } else {
          healthSkipped = true;
        }
      } catch (_) {
        failures.add('Apple Health');
      }
      if (!mounted) return;
      _reloadBriefAndHealth();
      if (widget.environment.hasSupabaseConfiguration) {
        try {
          await _makeDecisionCurrent();
        } catch (_) {
          failures.add('coach decision');
        }
      }
      if (!mounted) return;
      final String message;
      if (failures.isNotEmpty) {
        message = 'Synced, but unavailable: ${failures.join(', ')}.';
      } else if (healthSkipped) {
        message =
            'Synced. Apple Health is not connected — set it up in your profile.';
      } else {
        message = 'Everything is up to date.';
      }
      setState(() {
        _syncIssue = failures.isEmpty
            ? null
            : 'Could not refresh ${failures.join(' or ')}. Pull down or tap '
                  'Sync to try again.';
      });
      TracendToast.show(
        context,
        message,
        icon: failures.isEmpty
            ? CupertinoIcons.checkmark_alt
            : CupertinoIcons.exclamationmark_triangle,
      );
    } finally {
      if (mounted) setState(() => _syncing = false);
    }
  }

  String _dateKey(DateTime value) =>
      '${value.year.toString().padLeft(4, '0')}-'
      '${value.month.toString().padLeft(2, '0')}-'
      '${value.day.toString().padLeft(2, '0')}';

  /// Refreshes the coaching decision after new evidence arrived.
  ///
  /// The daily decision generates once per day, but it can be generated
  /// before the morning check-in — in that state the policy permits only
  /// gather-data actions and cites `recovery_check_in` as missing, and the
  /// card would keep saying "gather data" all day even after the check-in
  /// lands (the bar reads the live table, so the two contradicted each
  /// other). When today's decision cited the check-in as missing, a new
  /// decision is generated (new idempotency key → new audited row); the
  /// guardrails are unchanged, only the evidence is fresh. Failures are
  /// silent — the stale decision remains valid coaching.
  Future<void> _refreshDecisionAfterEvidence() async {
    if (!widget.environment.hasSupabaseConfiguration || !_aiAllowed) return;
    try {
      await _makeDecisionCurrent();
    } catch (_) {
      // Stale-but-valid decision stays on screen; the hero sync retries.
    }
  }

  /// The checks that make the decision current, one at a time: a check that
  /// starts while another is making a decision waits for it and then sees
  /// that decision, so one day never makes two.
  Future<void> _decisionChain = Future<void>.value();

  Future<void> _makeDecisionCurrent() {
    final check = _decisionChain.then((_) => _checkDecision());
    _decisionChain = check.then<void>((_) {}, onError: (_) {});
    return check;
  }

  Future<void> _checkDecision() async {
    final latest = await widget.coach.loadLatest();
    final today = _decisionDay();
    final citedCheckInMissing =
        latest != null &&
        latest.localDate == today &&
        latest.missingData.contains('recovery_check_in');
    // Checked again after the load: Today stays mounted while AI coaching
    // is turned off in Account, so the answer can change during the wait.
    if (_aiAllowed &&
        (latest == null || latest.localDate != today || citedCheckInMissing)) {
      await widget.coach.generate(localDate: today);
    }
    if (!mounted) return;
    setState(() {
      _latestDecision = widget.coach.loadLatest();
    });
  }

  Future<void> _openCheckIn() async {
    final saved = await showCheckInSheet(
      context,
      widget.environment,
      sender: widget.checkInSender,
      localDate: _serverDay,
    );
    if (saved && mounted) {
      final day = _dayKey();
      setState(() => _checkedInOn = day);
      _updateGate();
      // The widgets say the check-in is done at once: the brief reloaded
      // below can fail in the outage that queued the check-in.
      final brief = _lastBrief;
      if (brief != null) unawaited(_publishWidgets(brief));
      await _rememberDay(_checkedInKey, day);
    }
    if (mounted) {
      setState(() {
        _brief = _loadBrief();
      });
      // The check-in is what today's call rests on: read it again, and when
      // it sends the athlete to a professional, say so where it cannot be
      // missed.
      final readiness = widget.dayAdjustment;
      if (saved && readiness != null) {
        await readiness.load();
        if (mounted) await _showSafetyOnce(readiness);
      }
      if (mounted) await _refreshDecisionAfterEvidence();
    }
  }

  /// The referral sheet for a day with a safety route, shown once for that
  /// day and route.
  Future<void> _showSafetyOnce(DayAdjustmentController readiness) async {
    final adjustment = readiness.current;
    final route = adjustment?.safetyRoute;
    if (adjustment == null || route == null) return;
    final key = '${adjustment.localDate}:$route';
    if (_safetyShown == key) return;
    _safetyShown = key;
    await showDaySafetySheet(context, route);
  }

  /// Opens the brief's workout: the one planned for the date the brief was
  /// loaded for. A fixture brief carries no workout id, so its repository's
  /// workout opens instead.
  Future<void> _openWorkout(DailyBrief brief) async {
    final row = brief.workout;
    PlannedWorkout? workout;
    if (row != null && row['id'] is String) {
      workout = PlannedWorkout.fromHubJson(row);
    } else {
      try {
        workout = await widget.workouts?.loadTodayWorkout();
      } catch (e) {
        logNonCritical(e);
      }
    }
    if (workout == null || !mounted) return;
    final completed = await Navigator.of(context).push<bool>(
      CupertinoPageRoute(
        builder: (_) => WorkoutDetailScreen(
          repository: widget.workouts,
          dayAdjustment: widget.dayAdjustment,
          workout: workout,
          sessionDate: DateTime.tryParse(brief.localDate) ?? DateTime.now(),
        ),
      ),
    );
    // Whatever happened in the workout screen (saved, paused, finished), the
    // readiness card must say whether the session has started.
    unawaited(widget.dayAdjustment?.load());
    if (completed == true && mounted) {
      setState(() => _brief = _loadBrief());
    }
  }

  void _openAccount() => Navigator.of(context).push<void>(
    CupertinoPageRoute(
      builder: (_) => AccountScreen(
        environment: widget.environment,
        onSignOut: widget.onSignOut,
        health: widget.health,
        coach: widget.coach,
        widgetPublisher: widget.widgetPublisher,
        memory: widget.environment.hasSupabaseConfiguration
            ? SupabaseCoachMemoryRepository(Supabase.instance.client)
            : const FixtureCoachMemoryRepository(),
        notifications: widget.environment.hasSupabaseConfiguration
            ? SupabaseNotificationRepository(Supabase.instance.client)
            : const FixtureNotificationRepository(),
        exports: widget.environment.hasSupabaseConfiguration
            ? SupabasePrivacyExportRepository(Supabase.instance.client)
            : const FixturePrivacyExportRepository(),
        deletion: widget.environment.hasSupabaseConfiguration
            ? SupabaseAccountDeletionRepository(Supabase.instance.client)
            : const FixtureAccountDeletionRepository(),
        region: widget.environment.hasSupabaseConfiguration
            ? SupabaseRegionRepository(Supabase.instance.client)
            : const FixtureRegionRepository(),
        aiConsent: widget.aiConsent,
      ),
    ),
  );

  @override
  Widget build(BuildContext context) {
    final now = DateTime.now();
    // "Good afternoon" cannot fit a 320pt screen at the largest text sizes
    // without breaking a word, so there the title is "Today" and the
    // greeting moves into the subtitle.
    final compactTitle = MediaQuery.textScalerOf(context).scale(34) > 48;
    // Today's pressable rows and cards ink on this, so the screen also works
    // when it is mounted without a Scaffold.
    return Material(
      type: MaterialType.transparency,
      child: TracendScrollView(
        title: compactTitle ? 'Today' : _greeting(now),
        subtitle: compactTitle
            ? '${_greeting(now)}, ${_formattedDate(now)}'
            : _formattedDate(now),
        onRefresh: _syncEverything,
        trailing: AccountButton(onPressed: _openAccount),
        children: [
          FutureBuilder<DailyBrief>(
            future: _brief,
            builder: (context, snapshot) {
              // FutureBuilder retains the previous data when the future is
              // swapped (check-in / health sync reloads). Prefer it over the
              // waiting state so _BriefContent stays mounted: stagger
              // entrances don't replay and score count-ups animate on change.
              final brief = snapshot.data;
              if (brief != null) {
                return _BriefContent(
                  brief: brief,
                  targets: _targets,
                  meals: _meals,
                  latestDecision: _latestDecision,
                  aiAllowed: _aiAllowed,
                  healthHistory: _healthHistory,
                  syncing: _syncing,
                  syncIssue: _syncIssue,
                  onSync: _syncEverything,
                  onOpenNutrition: widget.onOpenNutrition,
                  onOpenWorkout:
                      widget.onOpenTrain ?? () => _openWorkout(brief),
                  onCheckIn: _openCheckIn,
                  checkedIn: _checkedIn(brief),
                  dayAdjustment: widget.dayAdjustment,
                  onTalkToCoach: widget.onTalkToCoach,
                  offerCheckIn:
                      widget.checkInGate == null ||
                      _skippedOn == brief.localDate,
                  unfinished: _unfinished,
                  answeringUnfinished: _answeringUnfinished,
                  onSaveUnfinished: _saveUnfinished,
                  onDiscardUnfinished: _discardUnfinished,
                );
              }
              if (snapshot.connectionState == ConnectionState.waiting) {
                return const _BriefSkeleton();
              }
              return TracendCard(
                child: Column(
                  crossAxisAlignment: CrossAxisAlignment.start,
                  children: [
                    Text(
                      'Use your approved plan.',
                      style: Theme.of(context).textTheme.headlineSmall,
                    ),
                    const SizedBox(height: TracendSpacing.xs),
                    const Text(
                      'The daily brief is unavailable. Workout and meal logging '
                      'remain available. Pull down to try again.',
                    ),
                  ],
                ),
              );
            },
          ),
        ],
      ),
    );
  }

  /// A plain greeting by the time of day; no name is invented.
  String _greeting(DateTime now) {
    if (now.hour >= 5 && now.hour < 12) return 'Good morning';
    if (now.hour >= 12 && now.hour < 18) return 'Good afternoon';
    return 'Good evening';
  }

  String _formattedDate(DateTime value) {
    const weekdays = [
      'Monday',
      'Tuesday',
      'Wednesday',
      'Thursday',
      'Friday',
      'Saturday',
      'Sunday',
    ];
    const months = [
      'January',
      'February',
      'March',
      'April',
      'May',
      'June',
      'July',
      'August',
      'September',
      'October',
      'November',
      'December',
    ];
    return '${weekdays[value.weekday - 1]} ${value.day} '
        '${months[value.month - 1]}';
  }
}

