/// The loaded brief, in reading order (UX_FLOWS.md §5): how recovered you
/// are and why (the tick ring), where the plan stands, sleep, load and fuel
/// at a glance, today's session with the coach's note, and the week so far.
class _BriefContent extends StatelessWidget {
  const _BriefContent({
    required this.brief,
    required this.targets,
    required this.meals,
    required this.latestDecision,
    required this.aiAllowed,
    required this.healthHistory,
    required this.syncing,
    required this.syncIssue,
    required this.onSync,
    required this.onOpenNutrition,
    required this.onOpenWorkout,
    required this.onCheckIn,
    required this.checkedIn,
    required this.offerCheckIn,
    required this.dayAdjustment,
    required this.onTalkToCoach,
    required this.unfinished,
    required this.answeringUnfinished,
    required this.onSaveUnfinished,
    required this.onDiscardUnfinished,
  });

  final DailyBrief brief;
  final Future<NutritionTargets?> targets;
  final Future<TodayMeals> meals;
  final Future<CoachDecision?> latestDecision;
  final bool aiAllowed;
  final Future<HealthHistory> healthHistory;
  final bool syncing;
  final String? syncIssue;
  final VoidCallback onSync;
  final VoidCallback? onOpenNutrition;
  final VoidCallback onOpenWorkout;
  final VoidCallback onCheckIn;
  final bool checkedIn;
  final bool offerCheckIn;
  final DayAdjustmentController? dayAdjustment;
  final ValueChanged<String>? onTalkToCoach;

  /// A workout logged and left unfinished, asked about right under the hero.
  final UnfinishedWorkout? unfinished;
  final bool answeringUnfinished;
  final ValueChanged<UnfinishedWorkout> onSaveUnfinished;
  final ValueChanged<UnfinishedWorkout> onDiscardUnfinished;

  @override
  Widget build(BuildContext context) {
    final colors = context.tracendColors;
    final unfinished = this.unfinished;
    final today = DateTime.tryParse(brief.localDate) ?? DateTime.now();
    final plan = brief.plan;
    var index = 0;
    Widget enter(Widget child) =>
        MicroMotionEntrance(delay: MicroMotion.stagger(index++), child: child);
    return Column(
      crossAxisAlignment: CrossAxisAlignment.stretch,
      children: [
        enter(
          TodayHero(
            brief: brief,
            onSync: onSync,
            syncing: syncing,
            syncIssue: syncIssue,
            checkedIn: checkedIn,
            offerCheckIn: offerCheckIn,
            onCheckIn: onCheckIn,
          ),
        ),
        if (unfinished != null) ...[
          const SizedBox(height: TracendSpacing.sm),
          enter(
            UnfinishedWorkoutCard(
              workout: unfinished,
              busy: answeringUnfinished,
              onSave: () => onSaveUnfinished(unfinished),
              onDiscard: () => onDiscardUnfinished(unfinished),
            ),
          ),
        ],
        if (plan != null) ...[
          const SizedBox(height: TracendSpacing.sm),
          enter(PlanProgressLine(plan: plan)),
        ],
        const SizedBox(height: TracendSpacing.md),
        enter(
          FutureBuilder<NutritionTargets?>(
            future: targets,
            builder: (context, targetSnapshot) => FutureBuilder<TodayMeals>(
              future: meals,
              builder: (context, mealSnapshot) => FutureBuilder<HealthHistory>(
                future: healthHistory,
                builder: (context, healthSnapshot) {
                  final todayMeals = mealSnapshot.data;
                  final targets = targetSnapshot.data;
                  return TodayTiles(
                    computed: brief.computed,
                    week: brief.week,
                    today: today,
                    consumed: brief.nutrition,
                    targets: targets,
                    fuelDay: todayMeals == null
                        ? null
                        : FuelDay.from(
                            proteinEaten:
                                ((brief.nutrition?['protein_g'] as num?) ?? 0)
                                    .toDouble(),
                            proteinTarget: targets?.protein,
                            schedule: todayMeals.schedule,
                            loggedMeals: todayMeals.meals,
                            now: DateTime.now(),
                          ),
                    sleepDay: _healthDay(healthSnapshot.data, today),
                    onLogMeal: onOpenNutrition,
                  );
                },
              ),
            ),
          ),
        ),
        const SizedBox(height: TracendSpacing.md),
        enter(
          FutureBuilder<CoachDecision?>(
            future: latestDecision,
            builder: (context, snapshot) => TodaySessionCard(
              brief: brief,
              decision: snapshot.data,
              aiAllowed: aiAllowed,
              onOpen: onOpenWorkout,
              dayAdjustment: dayAdjustment,
              onTalkToCoach: onTalkToCoach,
              onCheckIn: onCheckIn,
            ),
          ),
        ),
        if (brief.week.isNotEmpty) ...[
          const SizedBox(height: TracendSpacing.md),
          enter(YourWeekCard(week: brief.week, today: today)),
        ],
        const SizedBox(height: TracendSpacing.lg),
        Text(
          'Calculated from Apple Health and your logs. No AI in the numbers.',
          textAlign: TextAlign.center,
          style: Theme.of(
            context,
          ).textTheme.bodySmall?.copyWith(color: colors.textTertiary),
        ),
      ],
    );
  }

  /// Apple Health's summary for [day], when it has one.
  static HealthDay? _healthDay(HealthHistory? history, DateTime day) {
    if (history == null) return null;
    for (final entry in history.days) {
      final date = entry.date;
      if (date.year == day.year &&
          date.month == day.month &&
          date.day == day.day) {
        return entry;
      }
    }
    return null;
  }
}
